(()=>{'use strict';
const reduce=matchMedia('(prefers-reduced-motion: reduce)').matches;
const header=document.querySelector('.crisp-menu-app .topbar');
const hero=document.querySelector('.crisp-hero');
const product=document.querySelector('[data-hero-product]');
let ticking=false;
const update=()=>{const y=scrollY;
header?.classList.toggle('is-scrolled',y>12);
if(!reduce&&hero&&product){const progress=Math.min(1,Math.max(0,y/Math.max(hero.offsetHeight,1)));
const mobile=innerWidth<=780;
product.style.setProperty('--hero-y',`${progress*(mobile?22:68)}px`);
product.style.setProperty('--hero-rotate',`${-4+progress*7}deg`);
product.style.setProperty('--hero-scale',`${1-progress*(mobile?.04:.1)}`);
product.style.setProperty('--halo-scale',`${.86+progress*.13}`)}ticking=false};
addEventListener('scroll',()=>{if(!ticking){requestAnimationFrame(update);
ticking=true}},{passive:true});
addEventListener('resize',update,{passive:true});
update();
const items=document.querySelectorAll('[data-reveal]');
if(reduce||!('IntersectionObserver'in window))items.forEach(x=>x.classList.add('is-visible'));
else{const observer=new IntersectionObserver(entries=>entries.forEach(entry=>{if(entry.isIntersecting){entry.target.classList.add('is-visible');
observer.unobserve(entry.target)}}),{threshold:.12});
items.forEach(x=>observer.observe(x))}const go=()=>document.getElementById('menu')?.scrollIntoView({behavior:reduce?'auto':'smooth'});
document.getElementById('headerMenuLink')?.addEventListener('click',go);
document.getElementById('promoMenuButton')?.addEventListener('click',go)})();
